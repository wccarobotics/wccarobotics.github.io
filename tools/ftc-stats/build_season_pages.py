"""Build the BIOBUZZ season pages: an index of events that have qualification results, and a
qualification stats page for each one (generated by FtcStats.cs).

Usage (from anywhere in the repo):
    python tools/ftc-stats/build_season_pages.py [--season 2026] [--out tournaments/ftc/biobuzz]

Videos: livestream links from the FTC Events API are included automatically. Add videos found
elsewhere (e.g. by searching YouTube) to season-videos.json next to this script.
"""

import argparse
import base64
import datetime
import json
import re
import subprocess
import sys
import urllib.request
from pathlib import Path

TOOL_DIR = Path(__file__).resolve().parent
REPO = TOOL_DIR.parent.parent
SEASON_NAME = "BIOBUZZ"


def api(season, path, headers):
    url = f"https://ftc-api.firstinspires.org/v2.0/{season}/{path}"
    with urllib.request.urlopen(urllib.request.Request(url, headers=headers)) as resp:
        return json.load(resp)


def auth_headers():
    creds = json.loads((REPO / "ftc-api-credentials.json").read_text())
    token = base64.b64encode(f"{creds['username']}:{creds['auth_key']}".encode()).decode()
    return {"Authorization": "Basic " + token}


def is_played(m):
    """Same rule as Results.IsPlayed in FtcStats.cs: posted, or started with a nonzero score."""
    if m.get("scoreRedFinal") is None or m.get("scoreBlueFinal") is None:
        return False
    return bool(m.get("postResultTime")) or bool(m.get("actualStartTime")) and (m["scoreRedFinal"] > 0 or m["scoreBlueFinal"] > 0)


def video_id(url):
    m = re.search(r"(?:v=|youtu\.be/|/live/|/shorts/)([\w-]{11})", url or "")
    return m.group(1) if m else url


def event_videos(event, curated):
    # Curated entries come first, in the order listed; the API's livestream link is added
    # unless a curated entry already covers the same video.
    videos = {video_id(v["url"]): v for v in curated.get(event["code"], [])}
    if event.get("liveStreamUrl"):
        url = event["liveStreamUrl"].strip()
        vid = video_id(url)
        # Drop tracking parameters (?si=..., ?feature=share) from YouTube links.
        if vid != url:
            url = f"https://www.youtube.com/live/{vid}"
        videos.setdefault(vid, {"label": "Livestream", "url": url})
    # An entry marked "hide" suppresses a bad API link (e.g. a channel page with no recording).
    videos = {k: v for k, v in videos.items() if not v.get("hide")}
    return list(videos.values())


def format_dates(start, end):
    s = datetime.date.fromisoformat(start[:10])
    e = datetime.date.fromisoformat(end[:10])
    if s == e:
        return f"{s:%B} {s.day}, {s.year}"
    if s.month == e.month:
        return f"{s:%B} {s.day}–{e.day}, {s.year}"
    return f"{s:%B} {s.day} – {e:%B} {e.day}, {e.year}"


def short_date(start, end):
    s = datetime.date.fromisoformat(start[:10])
    e = datetime.date.fromisoformat(end[:10])
    if s == e:
        return f"{s:%b} {s.day}"
    return f"{s:%b} {s.day}–{e.day}" if s.month == e.month else f"{s:%b} {s.day} – {e:%b} {e.day}"


def location(event):
    if event.get("country") in ("USA", "Canada"):
        return f"{event['city']}, {event['stateprov']}"
    return f"{event['city']}, {event['country']}"


def stats_page(season, event, played, teams, videos, season_year):
    """Returns the stats page markdown and FtcStats' summary of the event (OPR, high score)."""
    summary_file = REPO / ".scratch" / "season-summaries" / f"{event['code']}.json"
    summary_file.parent.mkdir(parents=True, exist_ok=True)
    result = subprocess.run(
        ["dotnet", "run", "FtcStats.cs", "--", str(season), event["code"], "--markdown", "--no-title",
         "--summary", str(summary_file)]
        + (["--final"] if event["dateEnd"][:10] < datetime.date.today().isoformat() else []),
        cwd=TOOL_DIR, capture_output=True, text=True, encoding="utf-8")
    if result.returncode != 0:
        raise RuntimeError(f"FtcStats failed for {event['code']}:\n{result.stderr}{result.stdout}")
    summary = json.loads(summary_file.read_text(encoding="utf-8"))

    name = event["name"].strip()
    links = [f"[Results on FTC Events](https://ftc-events.firstinspires.org/{season}/{event['code']})"]
    links += [f"[{v['label']}]({v['url']})" for v in videos]
    # The title is written as a JSON string, which is also a valid YAML double-quoted string, so
    # event names containing quotes (NTX "Marcus Mayhem" Scrimmage) can't break the front matter.
    return summary, f"""---
layout: page
title: {json.dumps(name + " — Event Stats", ensure_ascii=False)}
---

# {name} — Event Stats

**{format_dates(event['dateStart'], event['dateEnd'])} · {location(event)} · {season_year} {SEASON_NAME} Season**

[← All {SEASON_NAME} events](./)

Rankings, OPR, schedule difficulty, and more, calculated from the {played} qualification matches played by {teams} teams, followed by the playoffs and awards when the event had them. The glossary at the bottom of the page explains each column.

**Tip:** Click on any team number to highlight all of that team's appearances on the page, or click a column heading to sort.

{" · ".join(links)}

{result.stdout.strip()}
"""


def index_page(rows, season_year, generated):
    lines = [
        "---",
        "layout: page",
        f'title: "{season_year} {SEASON_NAME} Events"',
        "---",
        "",
        f"# {season_year} {SEASON_NAME} Events",
        "",
        f"FIRST Tech Challenge events from the {season_year} {SEASON_NAME} season that have posted match results, "
        "most recent first, with a link to the livestream or video when we could find one. Click an event for its "
        "stats page: rankings, OPR, and schedule difficulty calculated from its qualification matches, the playoffs "
        "and awards, and a link to the official results.",
        "",
        "| Date | Event | Location | Teams | Quals | Avg OPR | Top OPR | High score | Winners | Video |",
        "|---|---|---|---:|---:|---:|---:|---:|---|---|",
    ]
    for r in rows:
        videos = " · ".join(f"[{v['label']}]({v['url']})" for v in r["videos"]) or "—"
        s = r.get("summary")
        if s:
            # With under 3 matches per team, OPR can't separate teams from their partners well.
            rough = "\\*" if s["qualsPlayed"] * 4 / s["teams"] < 3 else ""
            level = f"{s['avgOpr']:.1f}{rough} | {s['topOpr']:.1f}{rough} | {s['highScore']}"
        else:
            level = "— | — | —"
        # Events link to their stats page; practice-only events have none, so link the official results.
        link = f"./{r['code']}" if r["has_stats"] else f"https://ftc-events.firstinspires.org/{r['season']}/{r['code']}"
        winners = " / ".join(str(t) for t in (s or {}).get("winners") or []) or "—"
        lines.append(f"| {r['date']} | [{r['name']}]({link}) | {r['location']} | {r['teams']} | {r['played']} | "
                     f"{level} | {winners} | {videos} |")
    lines += [
        "",
        "**Avg OPR** is the points a typical robot at the event adds to its alliance's score, and **Top OPR** is the "
        "best robot's (OPR is explained on each stats page). **High score** is the highest alliance score in a "
        "qualification match. Together they give a rough idea of the level of competition. Expect them to rise as "
        "the season goes on, and treat them as rough at small events with only a few matches per team. "
        "Click a column heading to sort.",
        "",
        "\\* Fewer than 3 matches per team, so these OPRs are especially rough.",
        "",
        f"<small>Updated {generated:%B} {generated.day}, {generated.year}. Event and match data provided by the "
        "[FIRST Tech Challenge Events API](https://ftc-events.firstinspires.org/services/API).</small>",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--season", type=int, default=2026)
    parser.add_argument("--out", default="tournaments/ftc/biobuzz")
    args = parser.parse_args()

    headers = auth_headers()
    today = datetime.date.today()
    season_year = f"{args.season}–{(args.season + 1) % 100:02d}"
    curated = json.loads((TOOL_DIR / "season-videos.json").read_text(encoding="utf-8"))
    out = REPO / args.out
    out.mkdir(parents=True, exist_ok=True)

    events = api(args.season, "events", headers)["events"]
    candidates = sorted(
        (e for e in events if e["typeName"] != "Kickoff" and e["dateStart"][:10] <= today.isoformat()),
        key=lambda e: (e["dateStart"], e["code"]), reverse=True)

    rows = []
    for event in candidates:
        matches = api(args.season, f"matches/{event['code']}", headers)["matches"]
        all_played = [m for m in matches if is_played(m)]
        if not all_played:
            continue
        quals = [m for m in all_played if m["tournamentLevel"] == "QUALIFICATION"]
        teams = len({t["teamNumber"] for m in all_played for t in m["teams"]})
        videos = event_videos(event, curated)
        row = dict(season=args.season, code=event["code"], name=event["name"].strip(),
                   date=short_date(event["dateStart"], event["dateEnd"]), location=location(event),
                   teams=teams, played=len(quals), videos=videos)
        print(f"{event['code']}: {len(quals)} quals of {len(all_played)} matches, {teams} teams, "
              f"{len(videos)} video(s)", file=sys.stderr)
        if quals:
            row["summary"], page = stats_page(args.season, event, len(quals), teams, videos, season_year)
            (out / f"{event['code']}.md").write_text(page, encoding="utf-8", newline="\n")
            row["has_stats"] = True
        else:
            # Some scrimmages only run practice matches, which aren't ranked.
            row["played"] = f"{len(all_played)} practice"
            row["has_stats"] = False
        rows.append(row)

    (out / "index.md").write_text(index_page(rows, season_year, today), encoding="utf-8", newline="\n")
    print(f"Wrote {sum(1 for r in rows if r['played'] and isinstance(r['played'], int))} stats pages and an index of {len(rows)} events to {out}", file=sys.stderr)


if __name__ == "__main__":
    main()
